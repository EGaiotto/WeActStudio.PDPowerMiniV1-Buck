function applyI18n(root = document.body) {
  document.documentElement.lang = LANG;
  if (LANG === "pt-BR") return;
  const skip = new Set(["SCRIPT", "STYLE", "CODE", "PRE", "TEXTAREA"]);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (skip.has(n.parentElement?.tagName) || n.parentElement?.closest("[data-noi18n]") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    const raw = n.nodeValue, key = raw.replace(/\s+/g, " ").trim();
    if (!key || !(key in I18N)) continue;
    const lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0];
    n.nodeValue = (lead ? " " : "") + I18N[key][LI] + (trail ? " " : "");
  }
  for (const el of root.querySelectorAll("[title],[placeholder]")) {
    for (const a of ["title", "placeholder"]) {
      const v = el.getAttribute(a);
      if (v && I18N[v]) el.setAttribute(a, I18N[v][LI]);
    }
  }
  for (const el of root.querySelectorAll("[data-i18n]")) {
    const e = I18N_HTML[el.dataset.i18n];
    if (e) el.innerHTML = e[LI];
  }
}
